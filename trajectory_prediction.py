def train(X,Y,X_OUT,Y_OUT,model) :

    epochs = 20
    batch_size = 32
    steps = len(X)//batch_size

    for j in range(epochs) :
      data = data_pipeline(X,Y,X_OUT,Y_OUT,batch_size)
      model.fit(data,epochs = 1,steps_per_epoch = steps,verbose = 1)

