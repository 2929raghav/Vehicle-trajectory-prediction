import pandas as pd

sheet1 = pd.read_excel('converted_data_x_test.xlsx')
sheet2 = pd.read_excel('converted_data_Y_test.xlsx')

merged_df = pd.merge(sheet1, sheet2, on='ID')

# Creating a new dataframe with alternate columns from sheet1 and sheet2
result_df = pd.DataFrame()

# Assuming that the 'id' column is the first column in both sheets
result_df['ID'] = merged_df['ID']


for col in range(1, len(sheet1.columns)):
     result_df[f'Center_X{col}'] = merged_df[f'Center_X{col}']
     result_df[f'Center_Y{col}'] = merged_df[f'Center_Y{col}']

result_df.to_excel("xy_test.xlsx", index=False)

